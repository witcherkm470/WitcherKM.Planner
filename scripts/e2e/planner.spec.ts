import { test, expect } from "@playwright/test";
import { mockApi } from "./mockApi";

test("global task creation, card editing, lifecycle and keyboard focus", async ({ page }, testInfo) => {
    const api = await mockApi(page); const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
    await page.goto("/tasks");
    const trigger = page.getByRole("button", { name: /Добавить задачу/ });
    await trigger.click();
    const modal = page.getByRole("dialog", { name: "Новая задача" });
    await expect(modal.getByLabel("Название", { exact: true })).toBeFocused();
    await modal.getByLabel("Название", { exact: true }).fill("Проверить сценарий");
    await modal.getByLabel("Описание", { exact: true }).fill("Создание, редактирование и завершение задачи");
    await modal.getByRole("button", { name: "Фича", exact: true }).click();
    await modal.getByRole("option", { name: /Проект тестирования.*Первая фича/ }).click();
    await page.screenshot({ path: testInfo.outputPath("task-create.png"), fullPage: true });
    await modal.getByRole("button", { name: "Сохранить" }).focus(); await page.keyboard.press("Tab");
    await expect(modal.getByRole("button", { name: "Закрыть" })).toBeFocused();
    await modal.getByRole("button", { name: "Сохранить" }).click();
    await expect(modal).toHaveCount(0); await expect(trigger).toBeFocused();
    expect(api.tasks[0].featureId).toBe(2);
    await page.getByRole("link", { name: "Проверить сценарий", exact: true }).click();
    await expect(page.getByRole("link", { name: "Первая фича", exact: true })).toHaveAttribute("href", "/features/2");
    await page.getByRole("button", { name: "Редактировать задачу" }).click();
    const edit = page.getByRole("dialog", { name: "Редактирование задачи" });
    await edit.getByLabel("Название", { exact: true }).fill("Исправленная задача");
    await edit.getByRole("button", { name: "Сохранить" }).click();
    await expect(page.getByRole("heading", { name: "Исправленная задача" })).toBeVisible();
    await page.getByRole("button", { name: "Начать задачу" }).click();
    await expect(page.getByText("В работе", { exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("task-card.png"), fullPage: true });
    await page.getByRole("button", { name: "Завершить задачу" }).click();
    await expect(page.getByText("Готова", { exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "Редактировать задачу" })).toHaveCount(0);
    expect(api.unhandled).toEqual([]); expect(errors).toEqual([]);
});

test("project forms, documentation, scoped feature and task counters", async ({ page }, testInfo) => {
    const api = await mockApi(page);
    await page.goto("/projects");
    await page.getByRole("button", { name: /Добавить проект/ }).click();
    const projectModal = page.getByRole("dialog", { name: "Новый проект" });
    await projectModal.getByLabel("Название", { exact: true }).fill("Новый проект");
    await projectModal.getByRole("button", { name: "Создать" }).click();
    await page.getByRole("row").filter({ hasText: "Новый проект" }).getByRole("button", { name: "Редактировать проект" }).click();
    const editProject = page.getByRole("dialog", { name: "Редактирование проекта" });
    await editProject.getByLabel("Описание", { exact: true }).fill("Изменено");
    await editProject.getByRole("button", { name: "Сохранить" }).click();
    await expect(page.getByText("Изменено", { exact: true })).toBeVisible();
    await page.getByRole("link", { name: "Проект тестирования", exact: true }).click();
    await expect(page).toHaveURL(/\/projects\/1$/);
    await expect(page.getByRole("heading", { name: "Проект тестирования", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Редактировать проект" }).click();
    await page.getByLabel("Документация проекта").fill("Обновлённая документация");
    await page.getByRole("button", { name: "Завершить редактирование" }).click();
    await page.getByRole("dialog", { name: "Сохранить изменения?" }).getByRole("button", { name: "Да", exact: true }).click();
    await expect(page.getByText("Обновлённая документация", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: /Добавить фичу/ }).click();
    const featureModal = page.getByRole("dialog", { name: "Новая фича" });
    await featureModal.getByLabel("Название", { exact: true }).fill("Вторая фича");
    await featureModal.getByRole("button", { name: "Создать" }).click();
    await expect(page.getByText("Открытых фич: 2")).toBeVisible();
    await page.getByRole("link", { name: "Вторая фича", exact: true }).click();
    await page.getByRole("button", { name: /Добавить задачу/ }).click();
    const taskModal = page.getByRole("dialog", { name: "Новая задача" });
    await expect(taskModal.getByRole("button", { name: "Фича", exact: true })).toHaveCount(0);
    await taskModal.getByLabel("Название", { exact: true }).fill("Задача фичи");
    await taskModal.getByRole("button", { name: "Сохранить" }).click();
    await expect(page.getByText("Открытых задач: 1")).toBeVisible();
    await page.getByRole("button", { name: "Начать задачу" }).click();
    await expect(page.getByText("Открытых задач: 0")).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("feature-card.png"), fullPage: true });
    expect(api.tasks[0].featureId).toBe(api.features.find(f => f.name === "Вторая фича")!.id);
    expect(api.unhandled).toEqual([]);
});

test("idea forms and canceled filter preserve terminal behavior", async ({ page }) => {
    const api = await mockApi(page);
    await page.goto("/ideas"); await page.getByRole("button", { name: /Добавить идею/ }).click();
    await page.getByRole("dialog", { name: "Новая идея" }).getByLabel("Суть").fill("Исходная идея");
    await page.getByRole("button", { name: "Сохранить", exact: true }).click();
    await page.getByRole("button", { name: "Редактировать идею" }).click();
    await page.getByRole("dialog", { name: "Редактирование идеи" }).getByLabel("Суть").fill("Уточнённая идея");
    await page.getByRole("button", { name: "Сохранить", exact: true }).click();
    await page.getByRole("button", { name: "Отклонить", exact: true }).click();
    await expect(page.getByText("Идеи отсутствуют")).toBeVisible();
    await page.getByRole("button", { name: "Отклонённые", exact: true }).click();
    await expect(page.getByText("Уточнённая идея")).toBeVisible();
    await page.getByRole("button", { name: "Вернуть", exact: true }).click();
    await expect(page.getByText("Идеи отсутствуют")).toBeVisible();
    await page.getByRole("button", { name: "Активные", exact: true }).click();
    await page.getByRole("button", { name: "Реализовать", exact: true }).click();
    await expect(page.getByRole("button", { name: "Редактировать идею" })).toHaveCount(0);
    await expect(page.getByRole("button", { name: "Удалить идею" })).toHaveCount(0);
    expect(api.ideas[0].ideaStatus).toBe(1); expect(api.unhandled).toEqual([]);
});
